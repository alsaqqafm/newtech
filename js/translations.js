// Helper function to apply translations to all elements with data-i18n
function applyTranslations(lang) {
  const dictionary = translations[lang] || translations['ar'];
  
  // Update all text elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dictionary[key]) {
      el.textContent = dictionary[key];
    }
  });

  // Update placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dictionary[key]) {
      el.setAttribute('placeholder', dictionary[key]);
    }
  });

  // Update title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dictionary[key]) {
      el.setAttribute('title', dictionary[key]);
    }
  });

  // Update language toggle button text if present
  const langBtnText = document.querySelector('.lang-code-text');
  if (langBtnText) {
    langBtnText.textContent = lang === 'ar' ? 'English' : 'عربي';
  }
}
