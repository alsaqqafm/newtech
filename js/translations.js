// Global Translation Helper
function t(key) {
  const currentLang = document.documentElement.lang || 'ar';
  const dict = translations[currentLang] || translations['ar'];
  return dict[key] || key;
}

// Apply Translations to DOM dynamically without reload
function applyTranslations(lang) {
  const currentLang = (lang === 'en' || lang === 'ar') ? lang : (document.documentElement.lang || 'ar');
  const dictionary = translations[currentLang] || translations['ar'];

  // Update text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dictionary[key] !== undefined) {
      el.textContent = dictionary[key];
    }
  });

  // Update HTML content when marked with data-i18n-html
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dictionary[key] !== undefined) {
      el.innerHTML = dictionary[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dictionary[key] !== undefined) {
      el.setAttribute('placeholder', dictionary[key]);
    }
  });

  // Update titles
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dictionary[key] !== undefined) {
      el.setAttribute('title', dictionary[key]);
    }
  });

  // Update language toggle text
  document.querySelectorAll('.lang-code-text').forEach(btn => {
    btn.textContent = currentLang === 'ar' ? 'EN' : 'عربي';
  });

  // Update active state in navigation
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'en' ? 'ltr' : 'rtl';
}

